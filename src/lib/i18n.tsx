/* Fill every {placeholder} — .replace() only fills the first, which breaks
   "Both" mode where the placeholder appears in both languages. */
export function fill(template: string, vars: Record<string, string | number>): string {
  let out = template
  for (const [k, v] of Object.entries(vars)) out = out.split(`{${k}}`).join(String(v))
  return out
}

export function translate(lang: Lang, key: string): string {
  const e = en[key] ?? key
  if (lang === "en") return e
  const h = hi[key] ?? e
  if (lang === "hi") return h
  return `${e} (${h})`
}

/* ──────────────────────────────────────────────
   React context — language lives in localStorage so
   the shop owner's choice survives a refresh.
   ────────────────────────────────────────────── */
interface LanguageValue {
  lang: Lang
  setLang: (l: Lang) => void
  t: (key: string) => string
  /** t() + fill every {placeholder} — safe for "Both" mode */
  tx: (key: string, vars: Record<string, string | number>) => string
}

const LanguageContext = createContext<LanguageValue | null>(null)

const STORAGE_KEY = "voltkart-lang"

function loadLang(): Lang {
  try {
    const saved = localStorage.getItem(STORAGE_KEY)
    if (saved === "en" || saved === "hi" || saved === "both") return saved
  } catch {
    /* private mode — keep default */
  }
  return "en"
}

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>(loadLang)

  const setLang = useCallback((l: Lang) => {
    setLangState(l)
    try {
      localStorage.setItem(STORAGE_KEY, l)
    } catch {
      /* ignore */
    }
  }, [])

  const t = useCallback((key: string) => translate(lang, key), [lang])
  const tx = useCallback(
    (key: string, vars: Record<string, string | number>) => fill(translate(lang, key), vars),
    [lang]
  )

  return (
    <LanguageContext.Provider value={{ lang, setLang, t, tx }}>
      {children}
    </LanguageContext.Provider>
  )
}

export function useLanguage(): LanguageValue {
  const ctx = useContext(LanguageContext)
  if (!ctx) throw new Error("useLanguage must be used inside <LanguageProvider>")
  return ctx
}
